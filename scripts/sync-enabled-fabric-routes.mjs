import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, "..");
const fabricsDir = path.join(projectRoot, "src", "app", "fabrics");
const backendFile = path.join(projectRoot, "..", "vastraa-backend", "data", "enabledFabricRoutes.js");
const frontendFile = path.join(projectRoot, "src", "lib", "enabledFabricRoutes.ts");

const SLUG_ORDER = [
  "wholesale-cotton-fabrics",
  "wholesale-silk-fabrics",
  "wholesale-linen-fabrics",
  "wholesale-blended-fabrics",
  "wholesale-jute-fabric",
  "wholesale-modal-fabric",
  "wholesale-rayon-fabric",
  "wholesale-viscose-fabric",
  "wholesale-tencel-fabric",
  "greige",
  "knitted",
  "schiffli",
  "sustainable",
  "vinyl",
];

function detectFabricSlugs() {
  if (!fs.existsSync(fabricsDir)) return [];

  return fs
    .readdirSync(fabricsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("["))
    .filter((entry) => fs.existsSync(path.join(fabricsDir, entry.name, "page.tsx")))
    .map((entry) => entry.name.toLowerCase())
    .sort((a, b) => {
      const ai = SLUG_ORDER.indexOf(a);
      const bi = SLUG_ORDER.indexOf(b);
      return (ai === -1 ? 999 : ai) - (bi === -1 ? 999 : bi);
    });
}

function writeBackend(slugs) {
  const backendRoot = path.join(projectRoot, "..", "vastraa-backend");
  if (!fs.existsSync(backendRoot)) {
    console.log(
      "[sync-enabled-fabric-routes] Skipping backend sync (vastraa-backend not in workspace — OK for frontend-only CI)"
    );
    return;
  }

  const body = slugs.map((slug) => `    "${slug}",`).join("\n");
  const content = `/**
 * AUTO-GENERATED by scripts/sync-enabled-fabric-routes.mjs
 * Detected from src/app/fabrics/{slug}/page.tsx folders. Do not edit by hand.
 */
const ENABLED_FABRIC_SLUGS = [
${body}
];

function isEnabledFabricSlug(slug) {
    const key = String(slug || "").toLowerCase().trim();
    return ENABLED_FABRIC_SLUGS.includes(key);
}

module.exports = {
    ENABLED_FABRIC_SLUGS,
    isEnabledFabricSlug,
};
`;
  fs.mkdirSync(path.dirname(backendFile), { recursive: true });
  fs.writeFileSync(backendFile, content);
}

function writeFrontend(slugs) {
  const body = slugs.map((slug) => `  "${slug}",`).join("\n");
  const content = `/**
 * AUTO-GENERATED by scripts/sync-enabled-fabric-routes.mjs
 * Detected from src/app/fabrics/{slug}/page.tsx folders. Do not edit by hand.
 */
export const ENABLED_FABRIC_SLUGS = [
${body}
] as const;

export type EnabledFabricSlug = (typeof ENABLED_FABRIC_SLUGS)[number];

export function isEnabledFabricSlug(slug: string): boolean {
  return ENABLED_FABRIC_SLUGS.includes(slug.toLowerCase().trim() as EnabledFabricSlug);
}
`;
  fs.writeFileSync(frontendFile, content);
}

const slugs = detectFabricSlugs();
writeFrontend(slugs);
writeBackend(slugs);
console.log(`Synced ${slugs.length} fabric routes: ${slugs.join(", ")}`);
